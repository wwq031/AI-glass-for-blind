#!/usr/bin/env node
/**
 * Bakes the repository's JSON Schema files into a TypeScript module the WebView can import.
 *
 * The Node validator (`apps/gateway/src/tools/local-schema-validator.ts`) reads the schemas from
 * disk at startup. The phone bundle runs inside a WebView with no filesystem, so the same schemas
 * are embedded at build time instead of being re-declared by hand; `tests/scenarios/
 * mobile-agent-contracts.test.ts` fails if this file drifts from `packages/contracts/schemas`.
 *
 * Usage: node tools/build-mobile-contracts.mjs [--check]
 */
import { readFile, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const schemaDirectory = resolve(root, "packages/contracts/schemas");
const toolRegistryPath = resolve(root, "packages/providers/registry/tool-registry.json");
const outputPath = resolve(root, "apps/phone-companion/src/android/contract-schemas.generated.ts");

/** Every tool input schema in the registry, plus the result contracts the runtime validates. */
const RESULT_SCHEMAS = ["fact.schema.json", "destination-candidates.schema.json"];

const registry = JSON.parse(await readFile(toolRegistryPath, "utf8"));
const names = new Set(RESULT_SCHEMAS);
for (const tool of registry.tools) {
  const name = tool.input_schema.split("/").pop();
  if (!name?.endsWith(".schema.json")) throw new Error(`Unresolved input schema for ${tool.tool_id}`);
  names.add(name);
}

const entries = [];
for (const name of [...names].sort()) {
  const schema = JSON.parse(await readFile(resolve(schemaDirectory, name), "utf8"));
  if (typeof schema.$id !== "string") throw new Error(`${name} has no $id`);
  entries.push({ name, schema });
}

const contents = `// Generated by tools/build-mobile-contracts.mjs from packages/contracts/schemas. Do not edit.
//
// The Agent bundle runs in an Android WebView, which has no filesystem, so the contract schemas the
// phone runtime validates against are baked in here rather than read from disk. The Node validator
// keeps reading the same files directly; tests/scenarios/mobile-agent-contracts.test.ts compares
// this module against them so the two bindings cannot drift.
import type { JsonSchema } from "./contract-schemas.ts";

export const CONTRACT_SCHEMAS: Readonly<Record<string, JsonSchema>> = ${JSON.stringify(
  Object.fromEntries(entries.map(({ name, schema }) => [name, schema])),
  null,
  2,
)} as const;
`;

if (process.argv.includes("--check")) {
  const existing = await readFile(outputPath, "utf8").catch(() => "");
  if (existing !== contents) {
    console.error("contract-schemas.generated.ts is out of date; run: node tools/build-mobile-contracts.mjs");
    process.exit(1);
  }
  console.log(`contract schemas up to date (${entries.length} schemas)`);
} else {
  await writeFile(outputPath, contents, "utf8");
  console.log(`wrote ${entries.length} contract schemas to ${outputPath}`);
}
